#!/usr/bin/env node
/**
 * Concatenate src/client/*.js into client.js (the file the web host loads).
 * The fragments are plain statements inside one module factory, so the order is
 * the lexical order of the file names.
 *
 *   node scripts/build-client.mjs          # build
 *   node scripts/build-client.mjs --check  # verify client.js is up to date
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, renameSync, rmSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Script } from 'node:vm'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'src', 'client')
const outFile = join(root, 'client.js')
const checkOnly = process.argv.includes('--check')

const files = readdirSync(srcDir)
  .filter((name) => name.endsWith('.js'))
  .sort()

if (files.length === 0) {
  console.error('build-client: no fragments in src/client')
  process.exit(1)
}

const banner = `/* dsh-research-suite client bundle — generated by scripts/build-client.mjs; edit src/client/*.js */\n`
const body = files.map((name) => readFileSync(join(srcDir, name), 'utf8').trimEnd()).join('\n\n')
const output = `${banner}${body}\n`
// The Host loads this as a classic browser script. Parse before publishing it.
new Script(output, { filename: outFile })

if (checkOnly) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : ''
  if (current !== output) {
    console.error('build-client: client.js is stale — run `npm run build:client`')
    process.exit(1)
  }
  console.log(`build-client: client.js up to date (${files.length} fragments, ${Buffer.byteLength(output)} bytes)`)
  process.exit(0)
}

const tempFile = `${outFile}.${randomUUID()}.tmp`
try {
  writeFileSync(tempFile, output, { flag: 'wx' })
  renameSync(tempFile, outFile)
} finally {
  rmSync(tempFile, { force: true })
}
console.log(`build-client: wrote client.js (${files.length} fragments, ${Buffer.byteLength(output)} bytes)`)
